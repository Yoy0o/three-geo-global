/**
 * Generates src/core/egm96Grid.ts: EGM96 geoid undulation (meters above the
 * WGS84 ellipsoid) sampled on a 1-degree grid, stored as Int16 decimeters.
 *
 * The source model is the NGA EGM96 15' grid as packaged by `egm96-universal`
 * (MIT). Run with the path to that package's ESM build:
 *
 *   npm i --no-save egm96-universal@1.1.1
 *   node scripts/generate-egm96.mjs node_modules/egm96-universal/dist/egm96-universal.esm.js
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/generate-egm96.mjs <path to egm96-universal.esm.js>');
  process.exit(1);
}
const { meanSeaLevel } = await import(pathToFileURL(resolve(src)).href);

const ROWS = 181; // lat 90 .. -90
const COLS = 360; // lon -180 .. 179
const data = new Int16Array(ROWS * COLS);
let min = Infinity;
let max = -Infinity;
for (let r = 0; r < ROWS; r++) {
  const lat = 90 - r;
  for (let c = 0; c < COLS; c++) {
    const lon = -180 + c;
    const n = meanSeaLevel(lat, lon);
    min = Math.min(min, n);
    max = Math.max(max, n);
    data[r * COLS + c] = Math.round(n * 10);
  }
}
const b64 = Buffer.from(data.buffer).toString('base64');
const out = `// Generated by scripts/generate-egm96.mjs - do not edit.
// EGM96 geoid undulation on a 1-degree grid (${ROWS} rows from 90N, ${COLS} columns from 180W),
// Int16 little-endian, decimeters. Range ${min.toFixed(1)} .. ${max.toFixed(1)} m.
// Source: NGA EGM96 (public domain) via egm96-universal (MIT).
export const EGM96_ROWS = ${ROWS};
export const EGM96_COLS = ${COLS};
export const EGM96_GRID_BASE64 =
  '${b64}';
`;
writeFileSync(resolve('src/core/egm96Grid.ts'), out);
console.log(`wrote src/core/egm96Grid.ts (${(out.length / 1024).toFixed(0)} KB), range ${min.toFixed(2)}..${max.toFixed(2)} m`);
